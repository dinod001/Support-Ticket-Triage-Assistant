import asyncio
import os
import sys

# Ensure backend root is on sys.path
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))

from dotenv import load_dotenv
load_dotenv(os.path.join(os.path.dirname(__file__), "..", ".env"))

from app.core.config import settings
from app.services.llm_provider import GroqProvider
from app.services.triage_service import TriageService
from app.services.rag_service import RAGService
from app.core.database import SessionLocal, init_db
from app.models.ticket import Ticket


async def run_live_groq_test():
    print("=" * 70)
    print("🚀 LIVE GROQ AI PIPELINE & END-TO-END WORKFLOW TEST")
    print("=" * 70)

    # 1. Environment & Key Check
    api_key = settings.GROQ_API_KEY
    if not api_key:
        print("[ERROR] GROQ_API_KEY is missing from environment or .env!")
        return

    masked_key = api_key[:8] + "..." + api_key[-4:]
    print(f"1. Provider: {settings.LLM_PROVIDER}")
    print(f"   Model: {settings.GROQ_MODEL}")
    print(f"   API Key: {masked_key}")

    provider = GroqProvider()

    # 2. Test Direct Chat Connectivity
    print("\n2. Testing Direct Connection to Groq Cloud API...")
    try:
        ping_resp = await provider.generate_chat_completion(
            system_prompt="You are a helpful assistant.",
            user_prompt="Reply with the word 'PONG' only.",
            json_mode=False
        )
        print(f"   [OK] Groq Response: {ping_resp.strip()}")
    except Exception as e:
        print(f"   [FAIL] Direct call failed: {str(e)}")
        return

    # 3. Test AI Triage (Structured JSON Classification)
    print("\n3. Testing AI Triage with Structured JSON Output...")
    triage_service = TriageService(provider=provider)
    sample_title = "Damaged package received for order #ORD-8821"
    sample_desc = "Hi, my package arrived crushed and the monitor screen is completely broken. I am extremely upset and want my money back ASAP!"

    triage_result, was_fallback = await triage_service.execute_triage(
        title=sample_title,
        description=sample_desc
    )

    print(f"   Fallback Used? {was_fallback}")
    print(f"   Category:  {triage_result.category}")
    print(f"   Priority:  {triage_result.priority}")
    print(f"   Sentiment: {triage_result.sentiment}")
    print(f"   Summary:   {triage_result.summary}")
    print(f"   Entities:  {triage_result.entities}")
    assert triage_result.category in ["Damaged", "Refund"]
    assert triage_result.priority in ["high", "urgent"]
    print("   [OK] Triage classification passed schema validation!")

    # 4. Test Knowledge Base RAG Retrieval & Draft Reply
    print("\n4. Testing Knowledge Base RAG Retrieval & Drafting...")
    rag_service = RAGService(provider=provider)
    indexed_count = await rag_service.index_knowledge_base(force_reindex=True)
    print(f"   Indexed Chunks: {indexed_count}")

    draft_reply, cited_articles = await rag_service.generate_draft_reply(
        title=sample_title,
        description=sample_desc
    )

    print(f"   Cited Articles: {cited_articles}")
    print(f"\n   --- AI DRAFT REPLY GENERATED BY GROQ ---\n{draft_reply}\n   -----------------------------------------")
    assert len(cited_articles) > 0
    print("   [OK] RAG Reply drafted with source citations!")

    # 5. Test Database Persistence
    print("\n5. Testing Database Persistence...")
    init_db()
    db = SessionLocal()
    ticket = Ticket(
        title=sample_title,
        description=sample_desc,
        customer_email="angry.customer@example.com",
        status="open",
        category=triage_result.category,
        priority=triage_result.priority,
        sentiment=triage_result.sentiment,
        summary=triage_result.summary,
        entities=triage_result.entities,
        draft_reply=draft_reply,
        cited_articles=cited_articles
    )
    db.add(ticket)
    db.commit()
    db.refresh(ticket)
    print(f"   [OK] Ticket saved to database with ID: #{ticket.id}, Status: {ticket.status}")
    db.close()

    print("\n" + "=" * 70)
    print("🎉 FULL LIVE GROQ WORKFLOW COMPLETED 100% SUCCESSFULLY!")
    print("=" * 70)


if __name__ == "__main__":
    asyncio.run(run_live_groq_test())
